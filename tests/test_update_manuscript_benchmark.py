import unittest

from scripts.update_manuscript_benchmark import latex_rate, update_text


class UpdateManuscriptBenchmarkTest(unittest.TestCase):
    def test_latex_rate_rounding(self):
        self.assertEqual(latex_rate(12345.6), "$12{,}300$ mol/s")
        self.assertEqual(latex_rate(2345.6), "$2{,}350$ mol/s")

    def test_update_text_replaces_paragraph_caption_and_rows(self):
        text = (
            "\\textbf{Computational Cost.} Table~\\ref{tab:compute} summarizes training and\n"
            "inference costs. A single experiment trains in ${\\sim}5$--$6$ GPU-hours. The\n"
            "inference-throughput entries are provisional until regenerated from\n"
            "\\texttt{scripts/benchmark\\_inference.py} on a quiet RTX 4090D and saved as\n"
            "\\texttt{results/inference\\_benchmark.json}. Final submission should use that\n"
            "artifact as the source for the generator-only and end-to-end molecules/second\n"
            "claims.\n\n"
            "\\begin{table}[htbp]\n"
            "\\caption{\\textbf{Computational Cost} on a single RTX 4090D GPU. Training time is for 300 epochs. Inference-throughput rows are provisional until regenerated by \\texttt{scripts/benchmark\\_inference.py}.}\n"
            "Inference: generator only & \\multicolumn{2}{c}{${\\sim}47{,}000$ mol/s} \\\\\n"
            "Inference: end-to-end & \\multicolumn{2}{c}{${\\sim}12{,}000$ mol/s} \\\\\n"
        )
        bench = {
            "generator_mol_per_s": 51111.1,
            "end_to_end_mol_per_s": 9876.5,
            "num_samples": 20000,
            "batch_size": 1000,
            "device": "cuda",
            "nfe": 1,
            "two_pass_cfg": False,
        }
        updated = update_text(text, bench)
        self.assertIn("$51{,}100$ mol/s", updated)
        self.assertIn("$9{,}880$ mol/s", updated)
        self.assertNotIn("provisional", updated)
        self.assertEqual(update_text(updated, bench), updated)
        self.assertIn("two-pass CFG\ndisabled", updated)


if __name__ == "__main__":
    unittest.main()
