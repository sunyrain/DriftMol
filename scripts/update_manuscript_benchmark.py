#!/usr/bin/env python3
"""Synchronize the manuscript compute table with inference benchmark JSON."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BENCHMARK = ROOT / "results" / "inference_benchmark.json"
DEFAULT_PAPER = ROOT / "docs" / "PAPER_DRAFT.md"

COMPUTE_PARAGRAPH_RE = re.compile(
    r"\\textbf\{Computational Cost\.\} Table~\\ref\{tab:compute\} summarizes training and\n"
    r"inference costs\..*?\n\n\\begin\{table\}",
    re.DOTALL,
)

PROVISIONAL_CAPTION = (
    "\\caption{\\textbf{Computational Cost} on a single RTX 4090D GPU. "
    "Training time is for 300 epochs. Inference-throughput rows are provisional "
    "until regenerated by \\texttt{scripts/benchmark\\_inference.py}.}"
)

FINAL_CAPTION = (
    "\\caption{\\textbf{Computational Cost} on a single RTX 4090D GPU. "
    "Training time is for 300 epochs. Inference throughput is measured by "
    "\\texttt{scripts/benchmark\\_inference.py} using 1-NFE generation.}"
)


def load_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text())
    except Exception as exc:
        raise SystemExit(f"Could not read benchmark JSON at {path}: {exc}") from exc


def rounded_rate(value: float) -> int:
    if value >= 10_000:
        return int(round(value / 100.0) * 100)
    if value >= 1_000:
        return int(round(value / 10.0) * 10)
    return int(round(value))


def latex_rate(value: float) -> str:
    return "$" + f"{rounded_rate(float(value)):,}".replace(",", "{,}") + "$ mol/s"


def replace_line(text: str, prefix: str, replacement: str) -> str:
    lines = text.splitlines()
    replaced = False
    for idx, line in enumerate(lines):
        if line.startswith(prefix):
            lines[idx] = replacement
            replaced = True
    if not replaced:
        raise ValueError(f"Could not find line starting with {prefix!r}")
    return "\n".join(lines) + ("\n" if text.endswith("\n") else "")


def update_text(text: str, bench: dict) -> str:
    generator_rate = latex_rate(float(bench["generator_mol_per_s"]))
    end_to_end_rate = latex_rate(float(bench["end_to_end_mol_per_s"]))
    num_samples = int(bench.get("num_samples", 0))
    batch_size = int(bench.get("batch_size", 0))
    device = bench.get("device", "cuda")
    nfe = int(bench.get("nfe", 1))
    two_pass = bool(bench.get("two_pass_cfg", False))

    paragraph = (
        "\\textbf{Computational Cost.} Table~\\ref{tab:compute} summarizes training and\n"
        "inference costs. A single experiment trains in ${\\sim}5$--$6$ GPU-hours.\n"
        f"Inference throughput was measured on \\texttt{{{device}}} with {num_samples:,}\n"
        f"samples, batch size {batch_size:,}, NFE $={nfe}$, and two-pass CFG\n"
        f"{'enabled' if two_pass else 'disabled'}. The benchmark reports generator-only\n"
        f"throughput of {generator_rate} and end-to-end SELFIES decoding throughput of\n"
        f"{end_to_end_rate}."
    )
    replacement = paragraph + "\n\n\\begin{table}"
    text, n_replaced = COMPUTE_PARAGRAPH_RE.subn(lambda _match: replacement, text, count=1)
    if n_replaced != 1:
        raise ValueError("Could not replace computational-cost paragraph")

    if PROVISIONAL_CAPTION in text:
        text = text.replace(PROVISIONAL_CAPTION, FINAL_CAPTION, 1)

    text = replace_line(
        text,
        "Inference: generator only &",
        f"Inference: generator only & \\multicolumn{{2}}{{c}}{{{generator_rate}}} \\\\",
    )
    text = replace_line(
        text,
        "Inference: end-to-end &",
        f"Inference: end-to-end & \\multicolumn{{2}}{{c}}{{{end_to_end_rate}}} \\\\",
    )
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark", default=str(DEFAULT_BENCHMARK))
    parser.add_argument("--paper", default=str(DEFAULT_PAPER))
    parser.add_argument("--check", action="store_true", help="Do not write; fail if paper is out of sync.")
    args = parser.parse_args()

    benchmark_path = Path(args.benchmark)
    paper_path = Path(args.paper)
    if not benchmark_path.is_absolute():
        benchmark_path = ROOT / benchmark_path
    if not paper_path.is_absolute():
        paper_path = ROOT / paper_path

    bench = load_json(benchmark_path)
    original = paper_path.read_text()
    updated = update_text(original, bench)
    if args.check:
        if updated != original:
            raise SystemExit("Manuscript benchmark section is not synchronized.")
        return 0
    paper_path.write_text(updated)
    print(f"Updated {paper_path.relative_to(ROOT)} from {benchmark_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
